RLS_FUNCTIONS = """
CREATE FUNCTION app_company_id() RETURNS uuid LANGUAGE sql STABLE AS
$$ SELECT nullif(current_setting('app.company_id', true), '')::uuid $$;

CREATE FUNCTION app_user_id() RETURNS uuid LANGUAGE sql STABLE AS
$$ SELECT nullif(current_setting('app.user_id', true), '')::uuid $$;

CREATE FUNCTION app_is_platform() RETURNS boolean LANGUAGE sql STABLE AS
$$ SELECT coalesce(current_setting('app.platform', true), '') = 'on' $$;

CREATE FUNCTION app_can_see_plant(p_plant_id uuid) RETURNS boolean LANGUAGE sql STABLE AS
$$
    SELECT CASE coalesce(current_setting('app.plant_ids', true), '')
        WHEN '*' THEN true
        WHEN '' THEN false
        ELSE coalesce(
            p_plant_id = ANY (string_to_array(current_setting('app.plant_ids', true), ',')::uuid[]),
            false)
    END
$$;

-- Login and token refresh must find a user before the tenant is known. This is the only
-- function that bypasses RLS, and it reveals nothing but (id, company_id).
CREATE FUNCTION auth_find_user(p_username text, p_user_id uuid)
RETURNS TABLE (id uuid, company_id uuid)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS
$$
    SELECT u.id, u.company_id FROM users u
    WHERE (p_username IS NOT NULL AND u.username = lower(p_username))
       OR (p_user_id IS NOT NULL AND u.id = p_user_id)
$$;
REVOKE ALL ON FUNCTION auth_find_user(text, uuid) FROM PUBLIC;
"""

